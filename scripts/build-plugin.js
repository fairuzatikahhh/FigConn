#!/usr/bin/env node
// Concatenates plugin/src/*.js (sorted by name) into plugin/code.js.
// Figma loads a single main file, so handlers live in separate source files and share one scope.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "plugin", "src");
const files = readdirSync(srcDir).filter((f) => f.endsWith(".js")).sort();
const out = ["// GENERATED by scripts/build-plugin.js from plugin/src/*.js. Do not edit directly.\n"];
for (const f of files) out.push(`// ===== ${f} =====\n` + readFileSync(join(srcDir, f), "utf8").trimEnd() + "\n");
writeFileSync(join(root, "plugin", "code.js"), out.join("\n"));
console.error(`built plugin/code.js from ${files.length} files: ${files.join(", ")}`);
